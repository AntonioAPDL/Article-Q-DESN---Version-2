app_joint_qdesn_phase155_resolve_source_dir <- function(path) {
  if (grepl("^/", path)) {
    normalizePath(path, winslash = "/", mustWork = TRUE)
  } else {
    normalizePath(app_path(path), winslash = "/", mustWork = TRUE)
  }
}

app_joint_qdesn_phase155_read_source_metric <- function(source_dir, name) {
  path <- file.path(source_dir, name)
  if (!file.exists(path)) {
    stop(sprintf("Missing Phase155 source metric: %s", path), call. = FALSE)
  }
  app_read_csv(path)
}

app_joint_qdesn_phase155_aggregate_source_metrics <- function(case_summary) {
  source_map <- unique(case_summary[, c("source_block_id", "source_dir"), drop = FALSE])
  rows <- lapply(seq_len(nrow(source_map)), function(ii) {
    source_id <- source_map$source_block_id[[ii]]
    source_dir <- app_joint_qdesn_phase155_resolve_source_dir(source_map$source_dir[[ii]])
    crps <- app_joint_qdesn_phase155_read_source_metric(source_dir, "forecast_crps_grid_summary.csv")
    hit <- app_joint_qdesn_phase155_read_source_metric(source_dir, "forecast_hit_rate_summary.csv")
    chain <- app_joint_qdesn_phase155_read_source_metric(source_dir, "chain_to_pooled_distance_summary.csv")

    crps <- crps[toupper(crps$inference) == "MCMC", , drop = FALSE]
    hit <- hit[toupper(hit$inference) == "MCMC", , drop = FALSE]
    chain <- chain[toupper(chain$inference) == "MCMC", , drop = FALSE]
    cases <- unique(case_summary$case_id[case_summary$source_block_id == source_id])
    crps <- crps[crps$case_id %in% cases, , drop = FALSE]
    hit <- hit[hit$case_id %in% cases, , drop = FALSE]
    chain <- chain[chain$case_id %in% cases, , drop = FALSE]

    lapply(cases, function(case_id) {
      c_block <- crps[crps$case_id == case_id, , drop = FALSE]
      h_block <- hit[hit$case_id == case_id, , drop = FALSE]
      d_block <- chain[chain$case_id == case_id, , drop = FALSE]
      if (nrow(c_block) != 1L || !nrow(h_block) || !nrow(d_block)) {
        stop(sprintf("Incomplete source metrics for case '%s'.", case_id), call. = FALSE)
      }
      data.frame(
        case_id = case_id,
        mcmc_forecast_crps_grid = as.numeric(c_block$crps_grid_mean[[1L]]),
        mcmc_mean_abs_hit_rate_error = mean(as.numeric(h_block$abs_hit_rate_error), na.rm = TRUE),
        mcmc_max_abs_hit_rate_error = max(as.numeric(h_block$abs_hit_rate_error), na.rm = TRUE),
        max_chain_qhat_normalized_distance = max(as.numeric(d_block$qhat_normalized_to_pooled), na.rm = TRUE),
        max_chain_sigma_normalized_distance = max(as.numeric(d_block$sigma_normalized_to_pooled), na.rm = TRUE),
        max_chain_alpha_normalized_distance = max(as.numeric(d_block$alpha_normalized_to_pooled), na.rm = TRUE),
        source_block_id = source_id,
        stringsAsFactors = FALSE
      )
    })
  })
  app_joint_qdesn_bind_rows(unlist(rows, recursive = FALSE))
}

app_joint_qdesn_phase155_load <- function(
  phase154_dir = app_joint_qdesn_phase154_default_final_dir(),
  phase153_dir = app_joint_qdesn_phase153_default_vb_dir()
) {
  phase154_dir <- normalizePath(phase154_dir, winslash = "/", mustWork = TRUE)
  phase153_dir <- normalizePath(phase153_dir, winslash = "/", mustWork = TRUE)

  phase154_manifest <- app_joint_qdesn_phase155_verify_manifest(phase154_dir, "phase154_final")
  phase153_manifest <- app_joint_qdesn_phase155_verify_manifest(phase153_dir, "phase153_replication")
  phase154_source_manifest <- app_read_csv(file.path(phase154_dir, "source_manifest_verification.csv"))
  app_check_required_columns(phase154_source_manifest, c("source_id", "relative_path", "verified"), "Phase154 source verification")

  case_summary <- app_read_csv(file.path(phase154_dir, "final_mcmc_case_summary.csv"))
  case_assessment <- app_read_csv(file.path(phase154_dir, "final_mcmc_case_assessment.csv"))
  case_audit <- app_read_csv(file.path(phase154_dir, "final_case_audit.csv"))
  final_assessment <- app_read_csv(file.path(phase154_dir, "final_assessment.csv"))
  phase153_assessment <- app_read_csv(file.path(phase153_dir, "replication_assessment.csv"))
  phase153_contrasts <- app_read_csv(file.path(phase153_dir, "paired_contrast_summary.csv"))

  app_check_required_columns(case_summary, c(
    "case_id", "scenario_id", "source_model_id", "mcmc_fit_truth_mae",
    "mcmc_forecast_truth_mae", "mcmc_forecast_check_loss_mean",
    "mcmc_forecast_raw_crossing_pairs", "mcmc_forecast_contract_crossing_pairs",
    "mcmc_n_chains", "mcmc_n_iter", "mcmc_burn", "mcmc_thin",
    "mcmc_n_keep_total", "all_chain_init_source_provided",
    "mcmc_draws_all_finite", "source_block_id", "source_dir"
  ), "Phase154 final case summary")
  app_check_required_columns(case_assessment, c(
    "case_id", "implementation_status", "distance_status", "chain_status",
    "raw_crossing_status", "gate_status", "contract_crossing_pairs",
    "status_reason"
  ), "Phase154 final case assessment")
  app_check_required_columns(case_audit, c(
    "case_id", "exact_control_match", "article_grade", "final_status"
  ), "Phase154 final case audit")
  app_check_required_columns(phase153_contrasts, c(
    "base_scenario_id", "model_a", "model_b", "metric", "n_replicates",
    "median_delta", "model_a_win_fraction", "win_fraction_ci_lower",
    "win_fraction_ci_upper"
  ), "Phase153 paired contrasts")

  source_map <- unique(case_summary[, c("source_block_id", "source_dir"), drop = FALSE])
  source_manifests <- app_joint_qdesn_bind_rows(lapply(seq_len(nrow(source_map)), function(ii) {
    app_joint_qdesn_phase155_verify_manifest(
      app_joint_qdesn_phase155_resolve_source_dir(source_map$source_dir[[ii]]),
      source_map$source_block_id[[ii]]
    )
  }))
  extra_metrics <- app_joint_qdesn_phase155_aggregate_source_metrics(case_summary)

  idx <- match(case_summary$case_id, extra_metrics$case_id)
  if (anyNA(idx)) stop("Phase155 could not match all source metric rows.", call. = FALSE)
  for (name in setdiff(names(extra_metrics), c("case_id", "source_block_id"))) {
    case_summary[[name]] <- extra_metrics[[name]][idx]
  }
  assessment_idx <- match(case_summary$case_id, case_assessment$case_id)
  audit_idx <- match(case_summary$case_id, case_audit$case_id)
  if (anyNA(assessment_idx) || anyNA(audit_idx)) {
    stop("Phase155 could not match final assessment rows.", call. = FALSE)
  }
  for (name in c(
    "implementation_status", "distance_status", "chain_status",
    "raw_crossing_status", "gate_status", "status_reason"
  )) case_summary[[name]] <- case_assessment[[name]][assessment_idx]
  for (name in c("exact_control_match", "article_grade", "final_status")) {
    case_summary[[name]] <- case_audit[[name]][audit_idx]
  }

  models <- app_joint_qdesn_phase155_model_dictionary()
  scenarios <- app_joint_qdesn_phase155_scenario_dictionary()
  model_idx <- match(case_summary$source_model_id, models$source_model_id)
  scenario_idx <- match(case_summary$scenario_id, scenarios$scenario_id)
  if (anyNA(model_idx) || anyNA(scenario_idx)) {
    stop("Phase155 found an unknown scenario or model id.", call. = FALSE)
  }
  case_summary$model_label <- models$model_label[model_idx]
  case_summary$short_label <- models$short_label[model_idx]
  case_summary$model_order <- models$model_order[model_idx]
  case_summary$scenario_label <- scenarios$scenario_label[scenario_idx]
  case_summary$mechanism_detail <- scenarios$mechanism_detail[scenario_idx]
  case_summary$scenario_order <- scenarios$scenario_order[scenario_idx]
  case_summary <- case_summary[order(case_summary$scenario_order, case_summary$model_order), , drop = FALSE]
  rownames(case_summary) <- NULL

  list(
    phase154_dir = phase154_dir,
    phase153_dir = phase153_dir,
    phase154_manifest = phase154_manifest,
    phase153_manifest = phase153_manifest,
    phase154_source_manifest = phase154_source_manifest,
    source_manifests = source_manifests,
    case_summary = case_summary,
    case_assessment = case_assessment,
    case_audit = case_audit,
    final_assessment = final_assessment,
    phase153_assessment = phase153_assessment,
    phase153_contrasts = phase153_contrasts
  )
}

app_joint_qdesn_phase155_source_gate <- function(src) {
  x <- src$case_summary
  expected <- as.vector(outer(
    app_joint_qdesn_phase155_scenario_dictionary()$scenario_id,
    app_joint_qdesn_phase155_model_dictionary()$source_model_id,
    paste,
    sep = "::"
  ))
  cells <- paste(x$scenario_id, x$source_model_id, sep = "::")
  finite_cols <- c(
    "mcmc_fit_truth_mae", "mcmc_forecast_truth_mae",
    "mcmc_forecast_check_loss_mean", "mcmc_forecast_crps_grid",
    "mcmc_mean_abs_hit_rate_error", "max_chain_qhat_normalized_distance"
  )
  checks <- c(
    all(src$phase154_manifest$verified),
    all(src$phase153_manifest$verified),
    all(as.logical(src$phase154_source_manifest$verified)),
    all(src$source_manifests$verified),
    nrow(x) == 32L,
    !anyDuplicated(cells),
    setequal(cells, expected),
    all(vapply(x[finite_cols], function(z) all(is.finite(as.numeric(z))), logical(1L))),
    all(as.logical(x$exact_control_match)),
    all(as.logical(x$article_grade)),
    all(as.logical(x$all_chain_init_source_provided)),
    all(as.logical(x$mcmc_draws_all_finite)),
    all(x$implementation_status == "pass"),
    all(x$distance_status == "pass"),
    all(x$chain_status == "pass"),
    all(x$mcmc_forecast_contract_crossing_pairs == 0L),
    !any(x$final_status == "fail"),
    identical(as.character(src$final_assessment$recommendation[[1L]]), "build_article_assets_from_phase154_final_evidence"),
    as.integer(src$phase153_assessment$completed_candidates[[1L]]) == 1600L,
    as.integer(src$phase153_assessment$remaining_candidates[[1L]]) == 0L
  )
  if (all(checks)) "pass" else "fail"
}

app_joint_qdesn_phase155_metric_winners <- function(case_summary) {
  metrics <- c(
    mcmc_fit_truth_mae = "Fit MAE",
    mcmc_forecast_truth_mae = "Forecast MAE",
    mcmc_forecast_check_loss_mean = "Check loss",
    mcmc_forecast_crps_grid = "aCRPS"
  )
  rows <- lapply(unique(case_summary$scenario_id), function(scenario_id) {
    block <- case_summary[case_summary$scenario_id == scenario_id, , drop = FALSE]
    lapply(names(metrics), function(metric) {
      ord <- order(as.numeric(block[[metric]]), block$model_order)
      best <- block[ord[[1L]], , drop = FALSE]
      second <- block[ord[[2L]], , drop = FALSE]
      data.frame(
        scenario_id = scenario_id,
        scenario_label = best$scenario_label[[1L]],
        metric = metric,
        metric_label = unname(metrics[[metric]]),
        best_source_model_id = best$source_model_id[[1L]],
        best_model_label = best$model_label[[1L]],
        best_value = as.numeric(best[[metric]][[1L]]),
        second_source_model_id = second$source_model_id[[1L]],
        second_model_label = second$model_label[[1L]],
        second_value = as.numeric(second[[metric]][[1L]]),
        best_margin = as.numeric(second[[metric]][[1L]] - best[[metric]][[1L]]),
        stringsAsFactors = FALSE
      )
    })
  })
  app_joint_qdesn_bind_rows(unlist(rows, recursive = FALSE))
}

app_joint_qdesn_phase155_main_table_data <- function(case_summary) {
  models <- app_joint_qdesn_phase155_model_dictionary()
  scenarios <- app_joint_qdesn_phase155_scenario_dictionary()
  winners <- app_joint_qdesn_phase155_metric_winners(case_summary)
  winners <- winners[winners$metric == "mcmc_forecast_truth_mae", , drop = FALSE]
  rows <- lapply(seq_len(nrow(scenarios)), function(ii) {
    scenario <- scenarios[ii, , drop = FALSE]
    block <- case_summary[case_summary$scenario_id == scenario$scenario_id[[1L]], , drop = FALSE]
    out <- data.frame(
      scenario_id = scenario$scenario_id[[1L]],
      scenario_label = scenario$scenario_label[[1L]],
      mechanism_detail = scenario$mechanism_detail[[1L]],
      stringsAsFactors = FALSE
    )
    for (jj in seq_len(nrow(models))) {
      model_id <- models$source_model_id[[jj]]
      row <- block[block$source_model_id == model_id, , drop = FALSE]
      prefix <- model_id
      out[[paste0(prefix, "__forecast_mae")]] <- row$mcmc_forecast_truth_mae[[1L]]
      out[[paste0(prefix, "__fit_mae")]] <- row$mcmc_fit_truth_mae[[1L]]
      out[[paste0(prefix, "__raw_forecast_crossings")]] <- row$mcmc_forecast_raw_crossing_pairs[[1L]]
    }
    win <- winners[winners$scenario_id == scenario$scenario_id[[1L]], , drop = FALSE]
    out$winner_source_model_id <- win$best_source_model_id[[1L]]
    out$winner_model_label <- win$best_model_label[[1L]]
    out$winner_margin <- win$best_margin[[1L]]
    out
  })
  app_joint_qdesn_bind_rows(rows)
}

