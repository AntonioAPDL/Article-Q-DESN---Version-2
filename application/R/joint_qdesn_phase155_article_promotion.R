app_joint_qdesn_phase155_winner_table <- function(winners) {
  metrics <- c("Fit MAE", "Forecast MAE", "Check loss", "aCRPS")
  rows <- lapply(unique(winners$scenario_id), function(scenario_id) {
    block <- winners[winners$scenario_id == scenario_id, , drop = FALSE]
    values <- setNames(rep("--", length(metrics)), metrics)
    for (ii in seq_len(nrow(block))) {
      values[[block$metric_label[[ii]]]] <- sprintf(
        "%s (%s)",
        block$best_model_label[[ii]],
        app_joint_qdesn_phase155_fmt_num(block$best_value[[ii]], 3L)
      )
    }
    data.frame(
      Scenario = block$scenario_label[[1L]],
      `Fit MAE` = values[["Fit MAE"]],
      `Forecast MAE` = values[["Forecast MAE"]],
      `Check loss` = values[["Check loss"]],
      aCRPS = values[["aCRPS"]],
      stringsAsFactors = FALSE,
      check.names = FALSE
    )
  })
  app_joint_qdesn_bind_rows(rows)
}

app_joint_qdesn_phase155_replication_table <- function(contrasts) {
  keep <- contrasts$metric == "forecast_truth_mae" & (
    (contrasts$model_a == "joint_qdesn_rhs_vb" & contrasts$model_b == "joint_exqdesn_rhs_vb") |
      (contrasts$model_a == "qdesn_rhs_independent_vb" & contrasts$model_b == "exqdesn_rhs_independent_vb")
  )
  x <- contrasts[keep, , drop = FALSE]
  scenarios <- app_joint_qdesn_phase155_scenario_dictionary()
  rows <- lapply(seq_len(nrow(scenarios)), function(ii) {
    scenario_id <- scenarios$scenario_id[[ii]]
    block <- x[x$base_scenario_id == scenario_id, , drop = FALSE]
    joint <- block[block$model_a == "joint_qdesn_rhs_vb", , drop = FALSE]
    independent <- block[block$model_a == "qdesn_rhs_independent_vb", , drop = FALSE]
    if (nrow(joint) != 1L || nrow(independent) != 1L) {
      stop(sprintf("Missing Phase153 AL/exAL contrast for '%s'.", scenario_id), call. = FALSE)
    }
    data.frame(
      Scenario = scenarios$scenario_label[[ii]],
      `Joint: AL-exAL` = sprintf(
        "%s (%d%%)",
        app_joint_qdesn_phase155_fmt_num(joint$median_delta[[1L]], 3L),
        round(100 * joint$model_a_win_fraction[[1L]])
      ),
      `Independent: AL-exAL` = sprintf(
        "%s (%d%%)",
        app_joint_qdesn_phase155_fmt_num(independent$median_delta[[1L]], 3L),
        round(100 * independent$model_a_win_fraction[[1L]])
      ),
      Replicates = as.integer(joint$n_replicates[[1L]]),
      stringsAsFactors = FALSE,
      check.names = FALSE
    )
  })
  app_joint_qdesn_bind_rows(rows)
}

app_joint_qdesn_phase155_model_summary <- function(case_summary) {
  models <- app_joint_qdesn_phase155_model_dictionary()
  rows <- lapply(seq_len(nrow(models)), function(ii) {
    model <- models[ii, , drop = FALSE]
    block <- case_summary[case_summary$source_model_id == model$source_model_id[[1L]], , drop = FALSE]
    data.frame(
      source_model_id = model$source_model_id[[1L]],
      model_label = model$model_label[[1L]],
      n_cases = nrow(block),
      n_pass = sum(block$final_status == "pass"),
      n_review = sum(block$final_status == "review"),
      n_fail = sum(block$final_status == "fail"),
      median_fit_mae = stats::median(block$mcmc_fit_truth_mae),
      median_forecast_mae = stats::median(block$mcmc_forecast_truth_mae),
      median_check_loss = stats::median(block$mcmc_forecast_check_loss_mean),
      median_grid_crps = stats::median(block$mcmc_forecast_crps_grid),
      mean_abs_hit_rate_error = mean(block$mcmc_mean_abs_hit_rate_error),
      raw_forecast_crossings = sum(block$mcmc_forecast_raw_crossing_pairs),
      contract_forecast_crossings = sum(block$mcmc_forecast_contract_crossing_pairs),
      max_chain_qhat_normalized_distance = max(block$max_chain_qhat_normalized_distance),
      stringsAsFactors = FALSE
    )
  })
  app_joint_qdesn_bind_rows(rows)
}

