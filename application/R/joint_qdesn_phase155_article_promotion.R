app_joint_qdesn_run_phase155_article_audit <- function(
  phase155_dir = app_joint_qdesn_phase155_default_dir(),
  main_tex = app_path("main.tex"),
  supplement_tex = app_path("qdesn-supplement.tex"),
  out_dir = file.path(phase155_dir, "article_readiness_audit")
) {
  phase155_dir <- normalizePath(phase155_dir, winslash = "/", mustWork = TRUE)
  out_dir <- normalizePath(out_dir, winslash = "/", mustWork = FALSE)
  app_ensure_dir(out_dir)
  artifact <- app_joint_qdesn_phase155_verify_manifest(phase155_dir, "phase155")
  assets <- app_joint_qdesn_phase155_verify_article_manifest(file.path(phase155_dir, "article_asset_manifest.csv"))
  claims <- app_read_csv(file.path(phase155_dir, "article_claim_audit.csv"))
  promotion <- app_read_csv(file.path(phase155_dir, "promotion_assessment.csv"))
  table_data <- app_read_csv(file.path(phase155_dir, "final_case_summary.csv"))

  manuscript <- data.frame(
    check = c(
      "mcmc_confirmation_named", "replicated_vb_layer_named",
      "forecast_winner_pattern_updated", "fit_winner_pattern_updated",
      "raw_crossing_scope_updated", "contract_crossings_reported",
      "predictive_contract_preserved", "supplement_wrapper_present",
      "stale_five_of_eight_removed", "stale_gamma_sensitivity_claim_removed"
    ),
    status = c(
      ifelse(app_joint_qdesn_phase155_text_contains(main_tex, "balanced MCMC confirmation"), "pass", "fail"),
      ifelse(app_joint_qdesn_phase155_text_contains(main_tex, "50 independently generated fixtures"), "pass", "fail"),
      ifelse(app_joint_qdesn_phase155_text_contains(main_tex, "four of the eight") && app_joint_qdesn_phase155_text_contains(main_tex, "two scenarios each"), "pass", "fail"),
      ifelse(app_joint_qdesn_phase155_text_contains(main_tex, "six of the eight fit windows"), "pass", "fail"),
      ifelse(app_joint_qdesn_phase155_text_contains(main_tex, "24 of the 25 raw forecast-window crossings"), "pass", "fail"),
      ifelse(app_joint_qdesn_phase155_text_contains(main_tex, "zero crossings after the monotone reporting rule"), "pass", "fail"),
      ifelse(
        app_joint_qdesn_phase155_text_contains(main_tex, "quantile-grid readout paths") &&
          app_joint_qdesn_phase155_text_contains(main_tex, "scalar predictive density"),
        "pass",
        "fail"
      ),
      ifelse(app_joint_qdesn_phase155_text_contains(supplement_tex, "joint_qdesn_article_validation_provenance_tables.tex"), "pass", "fail"),
      ifelse(!app_joint_qdesn_phase155_text_contains(main_tex, "lowest-forecast-MAE row in five of the eight"), "pass", "fail"),
      ifelse(!app_joint_qdesn_phase155_text_contains(main_tex, "sampled-gamma exAL sensitivity rows"), "pass", "fail")
    ),
    stringsAsFactors = FALSE
  )
  data_checks <- data.frame(
    check = c(
      "phase155_manifest", "article_asset_manifest", "balanced_grid",
      "finite_scores", "exact_controls", "article_grade", "contract_crossings",
      "source_claim_audit", "promotion_gate"
    ),
    status = c(
      ifelse(all(artifact$verified), "pass", "fail"),
      ifelse(all(assets$verified), "pass", "fail"),
      ifelse(nrow(table_data) == 32L && length(unique(table_data$scenario_id)) == 8L && length(unique(table_data$source_model_id)) == 4L, "pass", "fail"),
      ifelse(all(is.finite(table_data$mcmc_forecast_truth_mae)), "pass", "fail"),
      ifelse(all(as.logical(table_data$exact_control_match)), "pass", "fail"),
      ifelse(all(as.logical(table_data$article_grade)), "pass", "fail"),
      ifelse(sum(table_data$mcmc_forecast_contract_crossing_pairs) == 0L, "pass", "fail"),
      ifelse(!any(claims$status == "fail"), "pass", "fail"),
      ifelse(identical(promotion$hard_implementation_gate[[1L]], "pass"), "pass", "fail")
    ),
    stringsAsFactors = FALSE
  )
  statuses <- c(manuscript$status, data_checks$status)
  audit_status <- if (any(statuses == "fail")) "fail" else if (any(claims$status == "review")) "review" else "pass"
  summary <- data.frame(
    phase_id = "phase155_article_readiness_audit",
    audit_status = audit_status,
    manifest_rows_verified = sum(artifact$verified),
    manifest_rows_total = nrow(artifact),
    article_assets_verified = sum(assets$verified),
    article_assets_total = nrow(assets),
    manuscript_checks_passed = sum(manuscript$status == "pass"),
    manuscript_checks_total = nrow(manuscript),
    failed_checks = sum(statuses == "fail"),
    recommendation = if (identical(audit_status, "fail")) "repair_before_article_use" else "phase155_article_assets_ready_with_raw_crossing_review_language",
    stringsAsFactors = FALSE
  )
  readme_path <- file.path(out_dir, "README.md")
  writeLines(c(
    "# Phase 155 Article Readiness Audit",
    "",
    sprintf("- Audit status: `%s`", audit_status),
    sprintf("- Cache hashes: `%d/%d`", summary$manifest_rows_verified[[1L]], summary$manifest_rows_total[[1L]]),
    sprintf("- Article assets: `%d/%d`", summary$article_assets_verified[[1L]], summary$article_assets_total[[1L]]),
    sprintf("- Manuscript checks: `%d/%d`", summary$manuscript_checks_passed[[1L]], summary$manuscript_checks_total[[1L]])
  ), readme_path, useBytes = TRUE)
  paths <- c(
    audit_summary = app_joint_qdesn_phase155_write_csv(summary, file.path(out_dir, "audit_summary.csv")),
    artifact_manifest_verification = app_joint_qdesn_phase155_write_csv(artifact, file.path(out_dir, "artifact_manifest_verification.csv")),
    article_asset_manifest_verification = app_joint_qdesn_phase155_write_csv(assets, file.path(out_dir, "article_asset_manifest_verification.csv")),
    manuscript_checks = app_joint_qdesn_phase155_write_csv(manuscript, file.path(out_dir, "manuscript_checks.csv")),
    data_checks = app_joint_qdesn_phase155_write_csv(data_checks, file.path(out_dir, "data_checks.csv")),
    provenance = app_joint_qdesn_phase155_write_csv(app_joint_qvp_provenance_rows(), file.path(out_dir, "provenance.csv")),
    readme = normalizePath(readme_path, winslash = "/", mustWork = TRUE)
  )
  old_manifest <- file.path(out_dir, "artifact_manifest.csv")
  if (file.exists(old_manifest)) unlink(old_manifest)
  manifest <- app_joint_qdesn_write_manifest(paths, out_dir)
  list(
    out_dir = out_dir,
    summary = summary,
    manuscript_checks = manuscript,
    data_checks = data_checks,
    paths = c(paths, artifact_manifest = manifest$manifest_path)
  )
}
