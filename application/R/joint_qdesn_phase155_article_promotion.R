app_joint_qdesn_phase155_verify_article_manifest <- function(path) {
  manifest <- app_read_csv(path)
  app_check_required_columns(manifest, c("label", "path", "size_bytes", "sha256"), "Phase155 article asset manifest")
  app_joint_qdesn_bind_rows(lapply(seq_len(nrow(manifest)), function(ii) {
    artifact <- if (grepl("^/", manifest$path[[ii]])) manifest$path[[ii]] else app_path(manifest$path[[ii]])
    exists <- file.exists(artifact)
    actual_sha <- if (exists) app_sha256_file(artifact) else NA_character_
    actual_size <- if (exists) as.numeric(file.info(artifact)$size) else NA_real_
    data.frame(
      label = manifest$label[[ii]],
      path = manifest$path[[ii]],
      exists = exists,
      declared_size_bytes = as.numeric(manifest$size_bytes[[ii]]),
      actual_size_bytes = actual_size,
      declared_sha256 = manifest$sha256[[ii]],
      actual_sha256 = actual_sha,
      verified = exists && identical(actual_size, as.numeric(manifest$size_bytes[[ii]])) && identical(tolower(actual_sha), tolower(manifest$sha256[[ii]])),
      stringsAsFactors = FALSE
    )
  }))
}

